const normalizeLanguage = (lng) => lng?.startsWith('ar') ? 'ar' : lng?.startsWith('en') ? 'en' : 'es';

const getTextNodes = (root) => {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
        acceptNode(node) {
            const parent = node.parentElement;
            if (!parent) return NodeFilter.FILTER_REJECT;
            if (['SCRIPT', 'STYLE', 'TEXTAREA', 'INPUT'].includes(parent.tagName)) return NodeFilter.FILTER_REJECT;
            if (!node.nodeValue || !node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
            return NodeFilter.FILTER_ACCEPT;
        }
    });

    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    return nodes;
};

export const applyRideDetailsRuntimePatch = (lng) => {
    if (typeof document === 'undefined') return;
    const lang = normalizeLanguage(lng);
    const config = rideDetailsRuntimeText[lang];
    if (!config) return;

    getTextNodes(document.body).forEach((node) => {
        const original = node.nodeValue.trim();
        if (config.pairs[original]) {
            node.nodeValue = node.nodeValue.replace(original, config.pairs[original]);
            return;
        }

        for (const [pattern, replacement] of config.contains) {
            if (pattern.test(original)) {
                node.nodeValue = node.nodeValue.replace(original, original.replace(pattern, replacement));
                return;
            }
        }
    });

    document.querySelectorAll('[title]').forEach((el) => {
        const title = el.getAttribute('title');
        if (config.pairs[title]) el.setAttribute('title', config.pairs[title]);
    });
};

export default applyRideDetailsRuntimePatch;
