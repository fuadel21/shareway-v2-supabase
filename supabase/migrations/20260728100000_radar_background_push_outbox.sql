-- Reliable background push queue for both radar modes.
-- Reuses public.notifications, public.push_subscriptions and the existing send-push Edge Function.

create table if not exists public.radar_push_outbox (
  id bigint generated by default as identity primary key,
  notification_id uuid not null unique,
  user_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending', 'processing', 'sent', 'failed')),
  attempts integer not null default 0 check (attempts >= 0),
  next_attempt_at timestamptz not null default now(),
  locked_at timestamptz,
  last_error text,
  sent_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists radar_push_outbox_pending_idx
on public.radar_push_outbox (status, next_attempt_at, created_at)
where status in ('pending', 'failed');

alter table public.radar_push_outbox enable row level security;
revoke all on public.radar_push_outbox from public, anon, authenticated;

create or replace function public.enqueue_radar_push_notification()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if coalesce(new.metadata->>'radar', 'false') <> 'true' then
    return new;
  end if;

  insert into public.radar_push_outbox (notification_id, user_id)
  values (new.id, new.user_id)
  on conflict (notification_id) do nothing;

  return new;
exception when others then
  raise warning 'Could not enqueue radar push for notification %: %', new.id, sqlerrm;
  return new;
end;
$$;

drop trigger if exists notifications_enqueue_radar_push on public.notifications;
create trigger notifications_enqueue_radar_push
after insert on public.notifications
for each row execute function public.enqueue_radar_push_notification();

create or replace function public.claim_radar_push_jobs(p_limit integer default 25)
returns table (
  job_id bigint,
  notification_id uuid,
  user_id uuid,
  title text,
  message text,
  action_url text,
  metadata jsonb,
  attempts integer
)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if coalesce(auth.role(), '') <> 'service_role' then
    raise exception 'SERVICE_ROLE_REQUIRED';
  end if;

  return query
  with candidates as (
    select o.id
    from public.radar_push_outbox o
    where (
      o.status = 'pending'
      or (o.status = 'failed' and o.next_attempt_at <= now())
      or (o.status = 'processing' and o.locked_at < now() - interval '10 minutes')
    )
      and o.attempts < 6
    order by o.created_at
    for update skip locked
    limit greatest(1, least(coalesce(p_limit, 25), 100))
  ), claimed as (
    update public.radar_push_outbox o
    set status = 'processing',
        attempts = o.attempts + 1,
        locked_at = now(),
        updated_at = now()
    from candidates c
    where o.id = c.id
    returning o.*
  )
  select
    c.id,
    c.notification_id,
    c.user_id,
    n.title,
    coalesce(n.message, ''),
    coalesce(n.action_url, '/notifications'),
    coalesce(n.metadata, '{}'::jsonb),
    c.attempts
  from claimed c
  join public.notifications n on n.id = c.notification_id;
end;
$$;

create or replace function public.finish_radar_push_job(
  p_job_id bigint,
  p_success boolean,
  p_error text default null
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if coalesce(auth.role(), '') <> 'service_role' then
    raise exception 'SERVICE_ROLE_REQUIRED';
  end if;

  update public.radar_push_outbox
  set status = case
        when p_success then 'sent'
        when attempts >= 6 then 'failed'
        else 'failed'
      end,
      sent_at = case when p_success then now() else sent_at end,
      next_attempt_at = case
        when p_success then next_attempt_at
        else now() + make_interval(mins => least(60, greatest(1, attempts * attempts)))
      end,
      locked_at = null,
      last_error = case when p_success then null else left(coalesce(p_error, 'Unknown push error'), 1000) end,
      updated_at = now()
  where id = p_job_id;
end;
$$;

revoke all on function public.claim_radar_push_jobs(integer) from public, anon, authenticated;
revoke all on function public.finish_radar_push_job(bigint, boolean, text) from public, anon, authenticated;
grant execute on function public.claim_radar_push_jobs(integer) to service_role;
grant execute on function public.finish_radar_push_job(bigint, boolean, text) to service_role;

comment on table public.radar_push_outbox is
  'Idempotent retry queue for background push delivery of driver and passenger radar notifications.';
