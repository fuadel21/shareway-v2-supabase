-- ShareWay notifications v1
-- In-app notifications with RLS and realtime-ready indexes.

create extension if not exists pgcrypto;

create table if not exists public.notifications (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  user_id uuid not null references auth.users(id) on delete cascade,
  actor_id uuid references auth.users(id) on delete set null,
  type text not null default 'system',
  title text not null,
  message text,
  action_url text,
  entity_type text,
  entity_id text,
  is_read boolean not null default false,
  read_at timestamptz,
  is_pinned boolean not null default false,
  priority text not null default 'normal' check (priority in ('low', 'normal', 'high', 'critical')),
  metadata jsonb not null default '{}'::jsonb
);

create index if not exists notifications_user_created_idx on public.notifications (user_id, created_at desc);
create index if not exists notifications_user_unread_idx on public.notifications (user_id, is_read, created_at desc);
create index if not exists notifications_user_type_idx on public.notifications (user_id, type, created_at desc);
create index if not exists notifications_entity_idx on public.notifications (entity_type, entity_id) where entity_type is not null and entity_id is not null;

alter table public.notifications enable row level security;

-- Admin helper that does not fail if profiles.is_admin or profiles.role do not exist yet.
create or replace function public.is_current_user_admin()
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_has_is_admin boolean := false;
  v_has_role boolean := false;
  v_result boolean := false;
begin
  if v_uid is null or to_regclass('public.profiles') is null then
    return false;
  end if;

  select exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'profiles'
      and column_name = 'is_admin'
  ) into v_has_is_admin;

  select exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'profiles'
      and column_name = 'role'
  ) into v_has_role;

  if v_has_is_admin then
    execute 'select coalesce(is_admin, false) from public.profiles where id = $1 limit 1'
    using v_uid
    into v_result;

    if coalesce(v_result, false) then
      return true;
    end if;
  end if;

  if v_has_role then
    execute 'select lower(coalesce(role, '''')) in (''admin'', ''super_admin'') from public.profiles where id = $1 limit 1'
    using v_uid
    into v_result;

    if coalesce(v_result, false) then
      return true;
    end if;
  end if;

  return false;
exception when others then
  raise warning '[notifications] admin helper fallback: %', sqlerrm;
  return false;
end;
$$;

grant execute on function public.is_current_user_admin() to authenticated;

-- Users can read their own notifications.
drop policy if exists "Users can read own notifications" on public.notifications;
create policy "Users can read own notifications"
on public.notifications
for select
to authenticated
using (auth.uid() = user_id);

-- Admins can read all notifications for moderation/support.
drop policy if exists "Admins can read all notifications" on public.notifications;
create policy "Admins can read all notifications"
on public.notifications
for select
to authenticated
using (public.is_current_user_admin());

-- Users can mark their own notifications as read/unread, pin/unpin them, and keep ownership unchanged.
drop policy if exists "Users can update own notifications" on public.notifications;
create policy "Users can update own notifications"
on public.notifications
for update
to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

-- Users can remove notifications from their own inbox.
drop policy if exists "Users can delete own notifications" on public.notifications;
create policy "Users can delete own notifications"
on public.notifications
for delete
to authenticated
using (auth.uid() = user_id);

-- Users may only create their own local/system notification records from the client.
-- Cross-user notifications are generated by triggers or trusted server flows, not arbitrary client inserts.
drop policy if exists "Users can create actor notifications" on public.notifications;
drop policy if exists "Users can create own notifications" on public.notifications;
create policy "Users can create own notifications"
on public.notifications
for insert
to authenticated
with check (auth.uid() = user_id and (actor_id is null or actor_id = auth.uid()));

-- Admins can create notifications for any user.
drop policy if exists "Admins can create notifications" on public.notifications;
create policy "Admins can create notifications"
on public.notifications
for insert
to authenticated
with check (public.is_current_user_admin());

create or replace function public.touch_notifications_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  if new.is_read = true and old.is_read = false and new.read_at is null then
    new.read_at = now();
  end if;
  if new.is_read = false then
    new.read_at = null;
  end if;
  return new;
end;
$$;

drop trigger if exists notifications_touch_updated_at on public.notifications;
create trigger notifications_touch_updated_at
before update on public.notifications
for each row
execute function public.touch_notifications_updated_at();

-- Enable Supabase Realtime for notification inserts/updates/deletes.
do $$
begin
  alter publication supabase_realtime add table public.notifications;
exception
  when duplicate_object then null;
  when undefined_object then null;
end $$;

-- Optional helper for admin dashboards.
create or replace view public.notification_unread_counts as
select
  user_id,
  count(*) filter (where is_read = false) as unread_count,
  count(*) as total_count,
  max(created_at) as latest_at
from public.notifications
group by user_id;
